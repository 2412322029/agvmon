"""开机自启：把 start_agvmon.ps1 写入当前用户的启动目录（shell:startup）。

方法约定：ps1 里用 Get-Command 沿 PATH 找到 agvmon 再拉起服务，依赖
agvmon.exe 所在目录已在用户 PATH 中（先执行 agvmon env add），因此换目录/
更新 exe 后无需改自启脚本。

注意：shell:startup 不会执行裸 .ps1（默认关联是记事本，开机只会打开它），
所以必须同时放一个 start_agvmon.cmd 启动器，用 powershell -File 调用 ps1；
-ExecutionPolicy Bypass 只对该次进程生效，不改系统执行策略。代价是登录
瞬间控制台一闪而过（vbs 方案完全无窗口，若不能接受可改回 vbs）。

启动目录取 %APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup，
即 shell:startup，只影响当前用户、不需要管理员权限。

本模块只依赖标准库；对 util.core.envpath 的引用也只在其内部（同样只依赖
标准库），无重依赖。
"""

import os
from pathlib import Path

PS1_NAME = "start_agvmon.ps1"  # 自启逻辑本体
CMD_NAME = "start_agvmon.cmd"  # 启动器：startup 不能直接执行 ps1
LEGACY_VBS_NAME = "start_agvmon.vbs"  # 旧版 vbs 方案遗留，add/remove 时一并清理
AGVMON_ARGS = "run web"  # 开机要拉起的服务，与 main.py 的 run web 一致


def _startup_dir() -> Path:
    """返回当前用户的启动目录（shell:startup 的实际路径）。"""
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("无法定位启动目录：环境变量 APPDATA 未设置")
    return (
        Path(appdata)
        / "Microsoft"
        / "Windows"
        / "Start Menu"
        / "Programs"
        / "Startup"
    )


def _ps1_text() -> str:
    """生成 ps1 内容；纯 ASCII（PowerShell 5.1 对无 BOM 文件按 ANSI 读取）。"""
    return "\n".join(
        [
            "# AGVmon autostart script (generated by 'agvmon autostart add').",
            "# Requires agvmon dir in user PATH (run 'agvmon env add' first).",
            "$cmd = Get-Command agvmon -ErrorAction SilentlyContinue",
            "if ($null -eq $cmd) { exit 1 }",
            "Start-Process -FilePath $cmd.Source -ArgumentList 'run', 'web' -WindowStyle Hidden",
            "",
        ]
    )


def _cmd_text() -> str:
    """生成 cmd 启动器；%~dp0 是启动器所在目录（启动目录），引号防路径空格。"""
    return "\n".join(
        [
            "@echo off",
            f'powershell -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "%~dp0{PS1_NAME}"',
            "",
        ]
    )


def _path_state():
    """返回 (是否已在 PATH, 异常说明)。agvmon 目录不存在等异常不中断主流程。"""
    from util.core.envpath import in_user_path

    try:
        return in_user_path(), ""
    except RuntimeError as e:
        return False, str(e)


def _remove_legacy_vbs() -> str | None:
    """清理旧版 vbs 方案遗留文件；存在则返回提示，否则 None。"""
    legacy = _startup_dir() / LEGACY_VBS_NAME
    if legacy.exists():
        legacy.unlink()
        return f"已清理旧版 vbs: {legacy}"
    return None


def add() -> str:
    """把 start_agvmon.ps1 + start_agvmon.cmd 写入启动目录（已存在则覆盖）。"""
    startup = _startup_dir()
    if not startup.is_dir():
        raise RuntimeError(f"启动目录不存在: {startup}")

    ps1 = startup / PS1_NAME
    cmd = startup / CMD_NAME
    existed = ps1.exists() or cmd.exists()
    ps1.write_text(_ps1_text(), encoding="ascii")
    cmd.write_text(_cmd_text(), encoding="ascii")

    lines = [
        f"已{'覆盖' if existed else '写入'}自启脚本: {ps1}",
        f"已{'覆盖' if existed else '写入'}启动器:   {cmd}",
        "（startup 不能直接执行 ps1，启动器负责以 powershell -File 调用）",
        f"开机执行: agvmon {AGVMON_ARGS}（隐藏窗口，登录瞬间控制台一闪而过）",
    ]
    legacy_note = _remove_legacy_vbs()
    if legacy_note:
        lines.append(legacy_note)

    in_path, note = _path_state()
    if in_path:
        lines.append("agvmon 目录已在用户 PATH 中，开机可正常拉起")
    else:
        lines.append("警告: agvmon 目录不在用户 PATH 中，开机时找不到 agvmon 命令")
        hint = "请先执行: agvmon env add"
        if note:
            hint += f"（{note}）"
        lines.append(f"  {hint}")
    return "\n".join(lines)


def remove() -> str:
    """从启动目录移除 ps1 与启动器（幂等；旧版 vbs 一并清理）。"""
    startup = _startup_dir()
    removed = []
    for name in (PS1_NAME, CMD_NAME):
        f = startup / name
        if f.exists():
            f.unlink()
            removed.append(str(f))

    legacy_note = _remove_legacy_vbs()
    if legacy_note:
        removed.append(_startup_dir() / LEGACY_VBS_NAME)

    if not removed:
        return f"启动目录中没有自启脚本，无需移除: {startup}"
    lines = [f"已移除自启脚本: {p}" for p in removed]
    return "\n".join(lines)


def show() -> str:
    """查看自启状态、脚本内容与 PATH 前置条件（只读）。"""
    startup = _startup_dir()
    ps1 = startup / PS1_NAME
    cmd = startup / CMD_NAME
    legacy = startup / LEGACY_VBS_NAME

    lines = [
        f"启动目录: {startup}",
        f"自启脚本: {'已存在' if ps1.exists() else '不存在'}  ({ps1})",
        f"启动器:   {'已存在' if cmd.exists() else '不存在'}  ({cmd})",
    ]
    if legacy.exists():
        lines.append(f"旧版 vbs: 仍存在，建议执行 autostart add 或 remove 清理  ({legacy})")
    if ps1.exists():
        lines.append("自启脚本内容:")
        content = ps1.read_text(encoding="ascii", errors="replace")
        lines.extend(f"  {line}" for line in content.splitlines())
    if cmd.exists():
        lines.append("启动器内容:")
        content = cmd.read_text(encoding="ascii", errors="replace")
        lines.extend(f"  {line}" for line in content.splitlines())

    in_path, note = _path_state()
    lines.append(f"agvmon 目录在用户 PATH 中: {'是' if in_path else '否'}")
    if note:
        lines.append(f"  ({note})")
    lines.append(f"开机执行: agvmon {AGVMON_ARGS}（隐藏窗口）")
    return "\n".join(lines)
